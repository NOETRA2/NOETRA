function dataRecord(result: Result) { return result.data.record as { id: string; revision: number; value: VisualState }; }
async function create(spec: unknown = brief) { const result = await engine.call('noetra.design_visual', { action: { kind: 'create', brief: spec } }); expect(result.ok).toBe(true); return dataRecord(result).id; }
async function act(designId: string, action: Record<string, unknown>) {
  return engine.call('noetra.design_visual', { action: { designId, expectedRevision: engine.memory.get(designId)!.revision, ...action } });
}
async function setup() {
  const designId = await create(), path = await imageFile('anchor.png', 30);
  const anchor = await act(designId, { kind: 'anchor', path, view: 'front-three-quarter' });
  return { designId, anchor: anchor.data.asset as { id: string }, path };
}
async function output(designId: string, shade = 100, view = 'front-three-quarter') {
  const plan = await act(designId, { kind: 'prepare', mode: view === 'front-three-quarter' ? 'detail-edit' : 'turnaround', view });
  expect(plan.ok).toBe(true);
  const job = plan.data.job as { id: string; referenceIds: string[] };
  const path = await imageFile(`output-${shade}-${view}.png`, shade);
  const attached = await act(designId, { kind: 'attach-output', path, jobId: job.id, sourceReferenceIds: job.referenceIds, generator: 'controlled test adapter' });
  expect(attached.ok).toBe(true);
  return { asset: attached.data.asset as { id: string }, job, path };
}
function matchingObservations(view = 'front-three-quarter') {
  return [{ featureId: 'silhouette', finding: 'match', note: 'Explicit reviewer assessment of the two files.' },
    ...(view === 'front' || view === 'front-three-quarter' ? [{ featureId: 'headlights', finding: 'match', measuredValue: 2, note: 'Two units reported by the reviewer.' }] : []),
    { featureId: 'panel-gaps', finding: 'match', note: 'Explicit detail reviewer assessment.' }];
}

